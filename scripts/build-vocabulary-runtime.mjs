import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const topics = JSON.parse(readFileSync(resolve(root, 'content/vocabulary/n5-topics.json'), 'utf8'));
const examples = JSON.parse(readFileSync(resolve(root, 'content/vocabulary/n5-examples.json'), 'utf8'));

const payload = {
  officialEntryCount: topics.recordCount,
  topics: topics.topics.map(topic => ({
    id: topic.id,
    name: topic.label,
    description: topic.description
  })),
  words: topics.words.map(word => ({
    sourceId: word.id,
    kana: word.kana,
    romaji: word.romaji,
    meaning: word.meaning,
    topicId: word.topicId,
    existingWordIds: word.existingWordIds || []
  })),
  examples: examples.examples
};

const output = `/* Generated by scripts/build-vocabulary-runtime.mjs. Do not edit directly. */\n` +
  `globalThis.KANA_SPRINT_N5_VOCABULARY = Object.freeze(${JSON.stringify(payload)});\n`;

writeFileSync(resolve(root, 'features/kana/vocabulary-n5.js'), output, 'utf8');
